"""Rebuild and validate the site's data files.

Usage:
    python build_data.py Acad_Program_Plan_codes_updated.xlsx          # rebuild data/plans.js
    python build_data.py --check                                       # validate data/*.js only
    python build_data.py Acad_Program_Plan_codes_updated.xlsx --check  # rebuild, then validate

Files (see README.md for the data model):
- data/plans.js      <- generated here from the Excel sheet (Sheet1: College, Degree,
                        Curriculum Version + link, plan code, Study Plan + link). Do not hand-edit.
- data/curricula.js  <- course lists, prerequisites, notes and total credits per curriculum
                        page, scraped from advisor.adu.ac.ae (refreshed by the scraper, not here).
- data/config.js     <- colleges (code, name, colour, sheet aliases), degree-level rules and
                        source info. Hand-edited; written here only if it does not exist yet.
- index.html         <- the page only; it contains no data.

Needs only openpyxl (and only when rebuilding from Excel). No network access.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data')

# Written to data/config.js the first time only; after that the file is the source of truth.
DEFAULT_CONFIG = {
    'colleges': [  # display order
        {'code': 'CAS', 'name': 'College of Arts and Sciences', 'color': '#E31B2A', 'aliases': []},
        {'code': 'COB', 'name': 'College of Business', 'color': '#2C333A', 'aliases': []},
        {'code': 'COE', 'name': 'College of Engineering', 'color': '#B3121F', 'aliases': []},
        {'code': 'CHS', 'name': 'College of Health Sciences', 'color': '#6B7280', 'aliases': ['CoHS']},
        {'code': 'COL', 'name': 'College of Law', 'color': '#E9A23B', 'aliases': ['CoL']},
    ],
    'levels': [  # first matching pattern wins (case-insensitive); unmatched degrees are "Other"
        {'name': 'Bachelor', 'pattern': '^Bachelor'},
        {'name': 'Master', 'pattern': '^(Master|Executive Master)'},
        {'name': 'Doctorate', 'pattern': '^Doctor'},
        {'name': 'Diploma', 'pattern': 'Diploma'},
        {'name': 'Associate', 'pattern': '^Associate'},
    ],
    'source': {'site': 'advisor.adu.ac.ae', 'scraped': '2026-11-11',
               'plan_sheet': 'Acad_Program_Plan_codes_updated.xlsx'},
}


def read_js(name):
    """Parse a data/*.js file of the form `// comment\\nwindow.X = <JSON>;`."""
    path = os.path.join(DATA, name)
    if not os.path.exists(path):
        return None
    txt = open(path, encoding='utf-8').read()
    body = txt.split('=', 1)[1].strip()
    return json.loads(body[:-1] if body.endswith(';') else body)


def ensure_config():
    path = os.path.join(DATA, 'config.js')
    if os.path.exists(path):
        return read_js('config.js')
    os.makedirs(DATA, exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// Site configuration — safe to edit by hand (build_data.py never overwrites it).\n'
                'window.ADU_CONFIG = ' + json.dumps(DEFAULT_CONFIG, ensure_ascii=False, indent=2) + ';\n')
    print('Wrote data/config.js (defaults)')
    return DEFAULT_CONFIG


def build(xlsx, cfg):
    import openpyxl
    fix = {a: c['code'] for c in cfg.get('colleges', []) for a in c.get('aliases', [])}
    ws = openpyxl.load_workbook(xlsx)['Sheet1']
    plans, col, deg = [], None, None
    for r in range(2, ws.max_row + 1):
        a, b, c, d, e = [ws.cell(r, i) for i in range(1, 6)]
        if a.value: col = fix.get(a.value, a.value)
        if b.value: deg = b.value
        if c.value is None: continue
        plans.append({'college': col, 'degree': deg, 'version': c.value,
                      'curriculum_url': c.hyperlink.target if c.hyperlink else '',
                      'plan_code': d.value or '', 'study_plan': e.value or '',
                      'study_plan_url': e.hyperlink.target if e.hyperlink else ''})
    with open(os.path.join(DATA, 'plans.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by build_data.py — do not edit by hand.\nwindow.ADU_PLANS = [\n')
        f.write(',\n'.join(json.dumps(p, ensure_ascii=False) for p in plans) + '\n];\n')
    print(f'Wrote data/plans.js with {len(plans)} curriculum versions')


def check(cfg):
    plans, cur = read_js('plans.js'), read_js('curricula.js')
    errors, warns = [], []
    if plans is None: errors.append('data/plans.js missing')
    if cur is None: errors.append('data/curricula.js missing')
    if errors:
        print('\n'.join('ERROR: ' + e for e in errors)); return 1
    known = {c['code'] for c in cfg.get('colleges', [])}
    seen = {}
    for i, p in enumerate(plans, 1):
        where = f"#{i} {p.get('college')} | {p.get('degree')!r} | {p.get('version')!r}"
        url = p.get('curriculum_url') or ''
        if url and url not in cur:
            errors.append(f'{where}: curriculum_url not in curricula.js: {url}')
        code = str(p.get('plan_code') or '').strip()
        if not code:
            errors.append(f'{where}: empty plan_code')
        elif code == '-' or ' ' in code and not any(ch.isdigit() for ch in code) and len(code) > 12:
            warns.append(f'{where}: plan_code looks like a placeholder ({code!r})')
        key = (p.get('degree'), p.get('version'), url)
        if key in seen:
            errors.append(f'{where}: duplicate (degree, version, curriculum page), same as #{seen[key]}')
        else:
            seen[key] = i
        if p.get('college') not in known:
            warns.append(f'{where}: college not listed in data/config.js')
    used = {p.get('curriculum_url') for p in plans}
    unused = [u for u in cur if u not in used]
    if unused:
        warns.append(f'{len(unused)} curricula.js entries not referenced by any plan')
    for w in warns: print('WARN: ' + w)
    for e in errors: print('ERROR: ' + e)
    n_courses = sum(len(c.get('courses', [])) for c in cur.values())
    progs = {(p['college'], p['degree']) for p in plans}
    print(f'Summary: {len(plans)} curriculum versions, {len(progs)} programs, '
          f'{len({p["plan_code"] for p in plans if p["plan_code"]})} plan codes, '
          f'{len(cur)} curriculum pages, {n_courses} course rows — '
          f'{len(errors)} error(s), {len(warns)} warning(s)')
    return 1 if errors else 0


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if a != '--check']
    do_check = '--check' in sys.argv[1:]
    cfg = ensure_config()
    if args or not do_check:
        build(args[0] if args else os.path.join(HERE, 'Acad_Program_Plan_codes_updated.xlsx'), cfg)
    if do_check:
        sys.exit(check(cfg))
